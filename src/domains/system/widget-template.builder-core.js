function normalizeWidgetPayload(input = {}) {
  const source = input && typeof input === "object" && !Array.isArray(input) ? input : {};
  const safeBaseUrl = String(source.baseUrl || "http://127.0.0.1:5050").trim().replace(/\/+$/, "");
  return {
    colorRewardId: String(source.colorRewardId || "").trim(),
    teachRewardId: String(source.teachRewardId || "").trim(),
    raveRewardId: String(source.raveRewardId || "").trim(),
    baseUrl: safeBaseUrl || "http://127.0.0.1:5050",
    raveAutoOffMs: Math.max(15000, Math.min(1800000, Math.round(Number(source.raveAutoOffMs) || 300000))),
    raveAutoOffResetOnRepeat: source.raveAutoOffResetOnRepeat !== false,
    colorRaveBlockedMessage: String(source.colorRaveBlockedMessage || "light commands are blocked while RAVE is active").trim(),
    twitchStatusSyncEnabled: source.twitchStatusSyncEnabled === true || source.statusSync === true,
    twitchClientId: String(source.twitchClientId || "").trim(),
    twitchUserAccessToken: String(source.twitchUserAccessToken || "").trim(),
    twitchBroadcasterId: String(source.twitchBroadcasterId || "").trim(),
    twitchOauthRedirectUri: String(source.twitchOauthRedirectUri || "").trim(),
    twitchOauthScopes: String(source.twitchOauthScopes || "channel:manage:redemptions").trim() || "channel:manage:redemptions",
    streamElementsBotChatEnabled: source.streamElementsBotChatEnabled === true || source.botEnabled === true,
    streamElementsBotChannelId: String(source.streamElementsBotChannelId || source.botChannelId || "").trim(),
    streamElementsBotJwt: String(source.streamElementsBotJwt || source.botJwt || "").trim(),
    streamElementsBotMessagePrefix: String(source.streamElementsBotMessagePrefix || source.botPrefix || "").trim(),
    raveOnNotifyEnabled: source.raveOnNotifyEnabled !== false,
    raveOnNotifyMessage: String(source.raveOnNotifyMessage || "RAVE is on, changing lights is disabled for {duration}.").trim() || "RAVE is on, changing lights is disabled for {duration}.",
    raveOffNotifyEnabled: source.raveOffNotifyEnabled !== false,
    raveOffNotifyMessage: String(source.raveOffNotifyMessage || "RAVE is over, lights can be changed again.").trim() || "RAVE is over, lights can be changed again.",
    colorFailureNotifyEnabled: source.colorFailureNotifyEnabled !== false,
    teachNotifyEnabled: source.teachNotifyEnabled !== false,
    colorChangeRedemptionName: String(source.colorChangeRedemptionName || source.changeColorRedemptionName || "change my lights").trim() || "change my lights"
  };
}

