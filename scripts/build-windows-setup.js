// [TITLE] Script: scripts/build-windows-setup.js
// [TITLE] Purpose: build Windows self-contained zip aliases and installer EXE
// [TITLE] Functionality Index:
// [TITLE] - ensure packaged release payload exists under dist/
// [TITLE] - create Windows-style self-contained zip alias
// [TITLE] - compile an Inno Setup installer when ISCC is available

const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const ROOT = path.resolve(__dirname, "..");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const VERSION = String(process.env.RAVELINK_RELEASE_VERSION || pkg.version || "1.6.2-dev")
  .trim()
  .replace(/-dev$/i, "");
const DIST_ROOT = path.join(ROOT, "dist");
const STAGE_DIR = path.join(DIST_ROOT, `RaveLink-Bridge-v${VERSION}`);
const PORTABLE_ZIP = path.join(DIST_ROOT, `RaveLink-Bridge-v${VERSION}.zip`);
const WINDOWS_ZIP = path.join(DIST_ROOT, `RaveLink-Bridge-Windows-v${VERSION}.zip`);
const SELF_CONTAINED_ZIP = path.join(DIST_ROOT, `RaveLink-Bridge-Windows-v${VERSION}-self-contained.zip`);
const INSTALLER_DIR = path.join(DIST_ROOT, "installer");
const INSTALLER_BASE = `RaveLink-Bridge-Windows-v${VERSION}-setup-installer`;
const ISS_PATH = path.join(INSTALLER_DIR, `${INSTALLER_BASE}.iss`);
const ISCC_CANDIDATES = [
  process.env.ISCC_PATH,
  "C:\\Program Files (x86)\\Inno Setup 6\\ISCC.exe",
  "C:\\Program Files\\Inno Setup 6\\ISCC.exe"
].filter(Boolean);

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd || ROOT,
    stdio: options.capture ? "pipe" : "inherit",
    encoding: "utf8",
    windowsHide: true
  });
  if (result.status !== 0) {
    const message = String(result.stderr || result.stdout || "").trim();
    throw new Error(`${command} exited with code ${result.status}${message ? `: ${message}` : ""}`);
  }
  return result;
}

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function fileExists(filePath) {
  try {
    return fs.existsSync(filePath);
  } catch {
    return false;
  }
}

function ensurePackagedRelease() {
  if (fileExists(STAGE_DIR) && fileExists(PORTABLE_ZIP)) return;
  run("npm.cmd", ["run", "package:release"]);
}

function copyFileIfNeeded(source, target) {
  if (!fileExists(source)) {
    throw new Error(`missing required file: ${source}`);
  }
  ensureDir(path.dirname(target));
  fs.copyFileSync(source, target);
}

function createZipFromDirectory(sourceDir, targetZip) {
  if (!fileExists(sourceDir)) {
    throw new Error(`missing required directory: ${sourceDir}`);
  }
  if (fileExists(targetZip)) fs.rmSync(targetZip, { force: true });
  const parentDir = path.dirname(sourceDir);
  const leafName = path.basename(sourceDir);
  try {
    // [DEV] tar.exe handles long Windows dependency paths more reliably than
    // System.IO.Compression in packaged node_modules trees.
    run("tar.exe", ["-a", "-c", "-f", targetZip, "-C", sourceDir, "."], {
      cwd: parentDir
    });
    return;
  } catch (tarError) {
    if (fileExists(targetZip)) {
      fs.rmSync(targetZip, { force: true });
    }
    const escapedSource = sourceDir.replace(/'/g, "''");
    const escapedTarget = targetZip.replace(/'/g, "''");
    const psScript = [
      "$ErrorActionPreference = 'Stop'",
      "Add-Type -AssemblyName 'System.IO.Compression.FileSystem'",
      `$source = '${escapedSource}'`,
      `$target = '${escapedTarget}'`,
      "[System.IO.Compression.ZipFile]::CreateFromDirectory($source, $target, [System.IO.Compression.CompressionLevel]::Optimal, $false)"
    ].join("; ");
    try {
      run("powershell.exe", [
        "-NoProfile",
        "-NonInteractive",
        "-ExecutionPolicy",
        "Bypass",
        "-Command",
        psScript
      ]);
      return;
    } catch (zipError) {
      throw new Error(`unable to create zip via tar.exe or powershell for ${leafName}: ${zipError.message || tarError.message}`);
    }
  }
}

function findIsccPath() {
  for (const candidate of ISCC_CANDIDATES) {
    if (fileExists(candidate)) return candidate;
  }
  const where = spawnSync("where.exe", ["ISCC.exe"], {
    cwd: ROOT,
    encoding: "utf8",
    stdio: "pipe",
    windowsHide: true
  });
  if (where.status === 0) {
    const lines = String(where.stdout || "").split(/\r?\n/).map(v => v.trim()).filter(Boolean);
    for (const line of lines) {
      if (fileExists(line)) return line;
    }
  }
  return "";
}

function innoString(value) {
  return String(value || "").replace(/\\/g, "\\\\");
}

function writeInstallerScript() {
  ensureDir(INSTALLER_DIR);
  const sourceDir = innoString(STAGE_DIR);
  const outputDir = innoString(DIST_ROOT);
  const outputBase = innoString(INSTALLER_BASE);
  const version = innoString(VERSION);

  const lines = [
    "; Generated by scripts/build-windows-setup.js",
    "#define AppName \"RaveLink Bridge\"",
    `#define AppVersion \"${version}\"`,
    `#define SourceDir \"${sourceDir}\"`,
    `#define OutputDir \"${outputDir}\"`,
    `#define OutputBaseFilename \"${outputBase}\"`,
    "",
    "[Setup]",
    "AppId={{CF817F37-5F04-4C18-A2B0-8A1EAA2674C5}",
    "AppName={#AppName}",
    "AppVersion={#AppVersion}",
    "AppPublisher=NameSRoby",
    "DefaultDirName={localappdata}\\Programs\\RaveLink Bridge",
    "UsePreviousAppDir=no",
    "DefaultGroupName=RaveLink Bridge",
    "PrivilegesRequired=lowest",
    "PrivilegesRequiredOverridesAllowed=dialog",
    "DisableDirPage=no",
    "DisableProgramGroupPage=yes",
    "OutputDir={#OutputDir}",
    "OutputBaseFilename={#OutputBaseFilename}",
    "Compression=lzma2",
    "SolidCompression=yes",
    "WizardStyle=modern",
    "ArchitecturesAllowed=x64compatible",
    "ArchitecturesInstallIn64BitMode=x64compatible",
    "",
    "[Languages]",
    "Name: \"english\"; MessagesFile: \"compiler:Default.isl\"",
    "",
    "[Tasks]",
    "Name: \"desktopicon\"; Description: \"Create a desktop shortcut\"; GroupDescription: \"Additional icons:\"; Flags: unchecked",
    "Name: \"audiotools\"; Description: \"Run optional audio tools installer after setup\"; GroupDescription: \"Optional tasks:\"; Flags: unchecked",
    "",
    "[Files]",
    "Source: \"{#SourceDir}\\*\"; DestDir: \"{app}\"; Flags: ignoreversion recursesubdirs createallsubdirs",
    "",
    "[Icons]",
    "Name: \"{group}\\RaveLink Bridge (Start)\"; Filename: \"{app}\\RaveLink-Bridge-Start.bat\"",
    "Name: \"{group}\\RaveLink Bridge (Stop)\"; Filename: \"{app}\\RaveLink-Bridge-Stop.bat\"",
    "Name: \"{group}\\RaveLink Bridge (Install Optional Audio Tools)\"; Filename: \"{app}\\RaveLink-Bridge-Install-Optional-Audio-Tools.bat\"",
    "Name: \"{group}\\RaveLink Bridge UI\"; Filename: \"http://127.0.0.1:5050\"",
    "Name: \"{group}\\Uninstall RaveLink Bridge\"; Filename: \"{uninstallexe}\"",
    "Name: \"{autodesktop}\\RaveLink Bridge\"; Filename: \"{app}\\RaveLink-Bridge-Start.bat\"; Tasks: desktopicon",
    "",
    "[Run]",
    "Filename: \"{app}\\RaveLink-Bridge-Install-Optional-Audio-Tools.bat\"; Description: \"Run optional audio tools installer\"; Flags: postinstall skipifsilent; Tasks: audiotools",
    "Filename: \"{app}\\RaveLink-Bridge-Start.bat\"; Description: \"Launch RaveLink Bridge\"; Flags: nowait postinstall skipifsilent"
  ];

  fs.writeFileSync(ISS_PATH, `${lines.join("\n")}\n`, "utf8");
}

function main() {
  if (process.platform !== "win32") {
    throw new Error("Windows setup build is only supported on Windows.");
  }

  ensurePackagedRelease();
  copyFileIfNeeded(PORTABLE_ZIP, WINDOWS_ZIP);
  createZipFromDirectory(STAGE_DIR, SELF_CONTAINED_ZIP);
  writeInstallerScript();

  const isccPath = findIsccPath();
  if (!isccPath) {
    console.log(`[build-windows-setup] Inno Setup compiler not found. Script written to ${ISS_PATH}`);
    return;
  }

  run(isccPath, [ISS_PATH]);
  console.log(`[build-windows-setup] Windows zip: ${WINDOWS_ZIP}`);
  console.log(`[build-windows-setup] Self-contained zip: ${SELF_CONTAINED_ZIP}`);
  console.log(`[build-windows-setup] Installer exe: ${path.join(DIST_ROOT, `${INSTALLER_BASE}.exe`)}`);
}

try {
  main();
} catch (error) {
  console.error(`[build-windows-setup][ERROR] ${error.message}`);
  process.exit(1);
}
